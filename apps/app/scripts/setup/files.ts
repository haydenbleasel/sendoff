import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

import { parse } from "jsonc-parser";
import type { z } from "zod";

import { deployConfig, instanceSchema } from "./instance";
import type { BaseConfig, Instance } from "./instance";
import { PAGES_WORKER, pagesConfig } from "./pages";

export const APP_DIR = path.resolve(import.meta.dirname, "../..");
export const INSTANCE_DIR = path.join(APP_DIR, ".sendoff");
export const INSTANCE_FILE = path.join(INSTANCE_DIR, "instance.json");
export const DEPLOY_CONFIG = path.join(INSTANCE_DIR, "wrangler.jsonc");
const PAGES_DIR = path.join(INSTANCE_DIR, "pages");
const BASE_CONFIG = path.join(APP_DIR, "wrangler.jsonc");
const PRIVATE_FILE_MODE = 0o600;

const partialInstance = instanceSchema.partial();

export type InstanceDraft = z.output<typeof partialInstance>;

const ensureDir = () => {
  mkdirSync(INSTANCE_DIR, { recursive: true });
};

/** Whatever setup has recorded so far (re-runs pick up where they left off). */
export const readInstanceDraft = (): InstanceDraft => {
  if (!existsSync(INSTANCE_FILE)) {
    return {};
  }

  const parsed = partialInstance.safeParse(
    JSON.parse(readFileSync(INSTANCE_FILE, "utf-8"))
  );

  return parsed.success ? parsed.data : {};
};

export const writeInstanceDraft = (draft: InstanceDraft): void => {
  ensureDir();
  writeFileSync(INSTANCE_FILE, `${JSON.stringify(draft, null, 2)}\n`);
};

export const readInstance = (): Instance => {
  const parsed = instanceSchema.safeParse(readInstanceDraft());

  if (!parsed.success) {
    throw new Error(
      "Sendoff isn't set up on this machine yet. Run `bun run setup` first."
    );
  }

  return parsed.data;
};

// SAFETY: wrangler.jsonc is this repo's own config file; Wrangler validates the output.
const readBaseConfig = () =>
  parse(readFileSync(BASE_CONFIG, "utf-8")) as BaseConfig;

export const writeDeployConfig = (instance: Instance): string => {
  ensureDir();
  writeFileSync(
    DEPLOY_CONFIG,
    `// Generated by \`bun run deploy\` from ../wrangler.jsonc and instance.json. Don't edit.\n${JSON.stringify(deployConfig(readBaseConfig(), instance), null, 2)}\n`
  );

  return DEPLOY_CONFIG;
};

/** Write the Pages project that fronts the Worker; returns its folder, for `wrangler pages deploy --cwd`. */
export const writePagesProject = (
  instance: Instance,
  project: string
): string => {
  mkdirSync(path.join(PAGES_DIR, "dist"), { recursive: true });
  writeFileSync(path.join(PAGES_DIR, "dist", "_worker.js"), PAGES_WORKER);
  writeFileSync(
    path.join(PAGES_DIR, "wrangler.jsonc"),
    `// Generated by \`bun run deploy\` from ../../wrangler.jsonc and instance.json. Don't edit.\n${JSON.stringify(pagesConfig(readBaseConfig(), instance, project), null, 2)}\n`
  );

  return PAGES_DIR;
};

/** Write secrets to a private temp file for `wrangler deploy --secrets-file`, and remove it after. */
export const withSecretsFile = <T>(
  secrets: Partial<Record<string, string>>,
  task: (file: string) => T
): T => {
  ensureDir();
  const file = path.join(INSTANCE_DIR, `secrets.${crypto.randomUUID()}.json`);

  writeFileSync(file, JSON.stringify(secrets), { mode: PRIVATE_FILE_MODE });
  chmodSync(file, PRIVATE_FILE_MODE);

  try {
    return task(file);
  } finally {
    rmSync(file, { force: true });
  }
};
